/**
 * Generates src/content/brand-icons.ts.
 *
 * Three sources, in order:
 *   simple-icons (CC0)          the default, 3400+ marks, all 24x24
 *   Font Awesome Free brands    CC BY 4.0, for marks simple-icons will not
 *                               redistribute (AWS, LinkedIn)
 *   TRACED                      neither package carries it, so the vendor's own
 *                               mark was traced to paths and kept below
 *
 * Inline path data rather than files in /public, because an <img> cannot inherit
 * currentColor and these have to tint from the design tokens. Both packages stay
 * devDependencies: nothing ships them at runtime.
 *
 * Trademarks remain with their owners. Using a mark to say which tools I have
 * worked with is nominative use, not endorsement.
 */
import { execSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import * as fa from "@fortawesome/free-brands-svg-icons";
import * as si from "simple-icons";

/** Brands used outside the stack list, e.g. profile links in the rail. */
const EXTRA = ["github", "linkedin", "applemusic"];

/**
 * Marks simple-icons does not carry, because their owners restrict
 * redistribution. Font Awesome Free ships them under CC BY 4.0.
 */
const FONT_AWESOME = { aws: "faAws", linkedin: "faLinkedin" };

/**
 * Marks neither package carries, traced from the vendor's own artwork.
 *
 * Here rather than as a file in /public for the same reason the other two
 * sources are inline: an <img> cannot inherit currentColor, and every mark on
 * this site is drawn in a colour the page owns. The trace is the outline only,
 * so the brand's own colour is not reproduced and does not need to be: no mark
 * here is drawn in its brand colour, including TypeScript's blue.
 *
 * `viewBox` is the mark's own bounding box rather than 24x24, the same way a
 * Font Awesome mark keeps its 512-unit box. StackMark scales whatever it gets.
 */
const TRACED = {
  appsflyer: {
    title: "AppsFlyer",
    viewBox: "0 0 423 458",
    path: "M184 119L186 113L191 106L273 4L279 0L284 0L289 3L292 7L362 132L366 142L366 156L362 164L280 266L274 272L270 274L266 274L261 271L256 263L189 142L184 129Z M0 136L2 132L5 130L158 130L169 135L175 140L179 146L234 246L251 278L251 285L246 290L92 290L83 286L74 278L71 273L4 149Z M272 291L274 288L277 287L314 286L368 286L375 289L381 297L418 364L423 374L422 378L419 380L382 381L327 381L320 378L313 368L275 299Z M200 367L204 359L252 299L256 295L261 294L267 300L302 365L308 377L309 385L303 396L255 456L252 458L248 458L245 455L204 381L200 372Z",
  },
};

function fromTraced(slug) {
  return TRACED[slug];
}

function fromSimpleIcons(slug) {
  const icon = si["si" + slug.charAt(0).toUpperCase() + slug.slice(1)];
  return icon && { title: icon.title, path: icon.path, viewBox: "0 0 24 24" };
}

function fromFontAwesome(slug) {
  const icon = fa[FONT_AWESOME[slug]];
  if (!icon) return undefined;
  const [w, h, , , path] = icon.icon;
  return {
    title: icon.iconName,
    path: Array.isArray(path) ? path[0] : path,
    viewBox: `0 0 ${w} ${h}`,
  };
}

const out = mkdtempSync(join(tmpdir(), "icons-"));
try {
  execSync(
    `yarn -s tsc src/content/stack.ts --outDir ${out} --module commonjs ` +
      `--moduleResolution node --target es2022 --skipLibCheck`,
    { stdio: "pipe" },
  );
  const { stack } = await import(pathToFileURL(join(out, "stack.js")).href);

  const resolve = (slug) => {
    const icon = fromSimpleIcons(slug) ?? fromFontAwesome(slug) ?? fromTraced(slug);
    if (!icon) throw new Error(`no mark available for "${slug}" in any source`);
    return icon;
  };

  // Keyed by STACK ID, not by slug: lookups happen as iconFor(item.id), and
  // several ids legitimately share one slug (expo and eas, react and react-native).
  const found = new Map();
  const missing = stack.filter((s) => !s.icon).map((s) => s.id);

  for (const item of stack) if (item.icon) found.set(item.id, resolve(item.icon));
  // Brands used outside the stack are keyed by their own name instead.
  for (const slug of EXTRA) found.set(slug, resolve(slug));

  const body = [...found]
    .map(
      ([slug, i]) =>
        `  "${slug}": {\n    title: ${JSON.stringify(i.title)},\n` +
        `    viewBox: ${JSON.stringify(i.viewBox)},\n    path: ${JSON.stringify(i.path)},\n  },`,
    )
    .join("\n");

  writeFileSync(
    "src/content/brand-icons.ts",
    `// GENERATED by \`yarn icons:sync\`. Do not edit.\n` +
      `//\n` +
      `// Sources: simple-icons (CC0) and Font Awesome Free (CC BY 4.0, which\n` +
      `// requires attribution: https://fontawesome.com). Trademarks remain with\n` +
      `// their owners.\n` +
      `//\n` +
      `// Stack entries with no mark, rendered as a monogram: ${missing.join(", ")}.\n\n` +
      `export type BrandIcon = { title: string; viewBox: string; path: string };\n\n` +
      `export const brandIcons: Record<string, BrandIcon> = {\n${body}\n};\n`,
  );
  console.log(`wrote ${found.size} marks; ${missing.length} stack entries use a monogram`);
  console.log(`  monogram: ${missing.join(", ") || "none"}`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
